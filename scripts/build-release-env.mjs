import fs from'node:fs/promises';import path from'node:path';import{fileURLToPath}from'node:url';
import {buildSeo} from './build-seo.mjs';
const project=fileURLToPath(new URL('../',import.meta.url));
export async function buildReleaseEnv(root=project,env=process.env){
 const context=env.CONTEXT||'',branch=env.BRANCH||'';
 const name=context==='production'?'production':context==='branch-deploy'&&branch==='staging'?'staging':'preview';
 if(env.APP_ENV&&env.APP_ENV!==name)throw Error('APP_ENV does not match the Netlify deploy context');
 if(branch.length>200||/[\r\n\x00]/.test(branch))throw Error('Invalid build branch');
 const version=JSON.parse(await fs.readFile(path.join(root,'public/version.json'),'utf8')).version;
 if(!/^\d+\.\d+\.\d+$/.test(version))throw Error('Invalid release version');
 const commit=/^[a-f0-9]{7,40}$/i.test(env.COMMIT_REF||'')?env.COMMIT_REF.slice(0,12):'locale';
 await fs.mkdir(path.join(root,'lib'),{recursive:true});
 await fs.writeFile(path.join(root,'lib/release-context.json'),JSON.stringify({context,branch})+'\n');
 await fs.writeFile(path.join(root,'public/env.json'),JSON.stringify(name==='production'?{env:name}:{env:name,version,commit})+'\n');
 const header=path.join(root,'public/_headers'),marker='# Generated by build-release-env.mjs';
 let existing;try{existing=await fs.readFile(header,'utf8');}catch(e){if(e.code!=='ENOENT')throw e;}
 if(existing&&!existing.startsWith(marker))throw Error('Refusing to overwrite existing custom headers');
 if(name==='production'){if(existing)await fs.unlink(header);}
 else await fs.writeFile(header,marker+'\n/*\n  X-Robots-Tag: noindex\n');
 await buildSeo(root,name==='production');
 return {env:name,version,commit};
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))console.log(JSON.stringify(await buildReleaseEnv(undefined,process.argv.includes('--production')?{...process.env,CONTEXT:'production'}:process.env)));
